"""Captured-input contracts at the combat extractor's real engine boundary.

GAME04 T4 lines256-278 supplies the input. Expected character identities and
turn are read literally, not generated by an engine round trip. This fixture
also contains historical mirror duplicates; it does not certify the whole
reconstructed board or every extracted label.
"""
import ast
from collections import Counter, defaultdict
import importlib.util
import os
from pathlib import Path
import unittest
from unittest.mock import patch

import ai
import game_state as gs
import rendered_extract as rx

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / 'audit/2026-09-04/decision_pass/combat_reconstruction'
if os.environ.get('WOTR_AUDIT_COMBAT_RX_BASELINE'):
    spec = importlib.util.spec_from_file_location(
        'combat_rx_baseline', os.environ['WOTR_AUDIT_COMBAT_RX_BASELINE'])
    rx = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(rx)


class CapturedCombatReconstruction(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        batch = ast.literal_eval((EVIDENCE / 'captured_batch.literal').read_text(encoding='utf-8'))
        cls.stats = defaultdict(Counter)
        cls.first = None
        original = ai.get_legal_actions

        def observe(state, side):
            if cls.first is None:
                cls.first = ai.clone_state(state)
            return original(state, side)

        with patch.object(ai, 'get_legal_actions', side_effect=observe):
            cls.samples = rx._emit_combat_family(batch, cls.stats)

    def test_named_companions_are_companions_before_legal_enumeration(self):
        self.assertIsNotNone(self.first)
        for region, name, level, leadership in (
                ('lorien', 'Legolas', 2, 1),
                ('minas tirith', 'Boromir', 2, 1),
                ('westemnet', 'Aragorn', 3, 2)):
            with self.subTest(character=name):
                leader = next(l for l in self.first.armies[region].leaders
                              if getattr(l, 'name', None) == name)
                self.assertIsInstance(leader, gs.Companion)
                self.assertEqual((leader.level, leader.leadership), (level, leadership))

    def test_recorded_turn_and_crowned_hero_reach_the_same_boundary(self):
        self.assertEqual(self.first.turn, 4)
        self.assertTrue(self.first.aragorn_crowned.crowned)

    def test_real_card_gestures_reach_combat_sampling_without_type_error(self):
        self.assertEqual(self.stats['drop_reasons']['cc_legal_exc'], 0)
        self.assertFalse(any(k.startswith('cc_drive_exc:Unsupported')
                             for k in self.stats['drop_reasons']))
        # Both players explicitly reveal a combat card before the first roll.
        self.assertGreaterEqual(sum(s['phase'] == 'combat_card' for s in self.samples), 2)


if __name__ == '__main__':
    unittest.main(verbosity=2)

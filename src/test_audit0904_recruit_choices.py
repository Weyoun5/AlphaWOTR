"""Guards of the Citadel: independent player-choice acceptance tests.

Oracle, supplied second-edition rulebook / Card Almanac v98:
  * RB7: Gondor has 15 Regulars, 5 Elites and 4 Leaders.
  * RB16: Minas Tirith starts with 3 Regulars, 1 Elite, 1 Leader.
  * Guards (FP Strategy14): one Gondor Regular OR Elite AND one Leader.
  * RB22,27 / AL21-22: perform each feasible compulsory placement;
    event recruitment need not wait for At War, permits the stated siege
    exceptions, and can overstack before the owner returns excess figures.

These expected choices/counts are literal, not generated by the engine.
Every recruitment test enters through a public play_event action. The
prospective-encoding control deliberately isolates the currently missing
representation from the currently missing legal menu. No other test module
or TestCase is imported, and no corpus/model/release is modified.
"""
from collections import Counter
import copy
import unittest

import ai
import board
import game_logic as gl
import game_state as gs


FP, SH = gs.Side.FREE_PEOPLES, gs.Side.SHADOW
GONDOR, SAURON = gs.Nation.GONDOR, gs.Nation.SAURON
REGULAR, ELITE = gs.UnitKind.REGULAR, gs.UnitKind.ELITE
CID = 'FREE_PEOPLES_Strategy_Guards_of_the_Citadel'
TITLE = 'Guards of the Citadel'
MT = 'minas tirith'


def army(state, region=MT):
    return next((a for name, a in state.armies.items()
                 if board.sanitize(name) == board.sanitize(region)), None)


def gondor_figures(state):
    """Read raw figures, independently of the recruit/count helpers."""
    a = army(state)
    if a is None:
        return (0, 0, 0)
    return (sum(u.nation == GONDOR and u.kind == REGULAR for u in a.units),
            sum(u.nation == GONDOR and u.kind == ELITE for u in a.units),
            sum(isinstance(l, gs.Leader) and l.nation == GONDOR
                for l in a.leaders))


def other_armies(state):
    """Raw-piece inventory outside the affected region, not a renderer diff."""
    out = {}
    for name, a in state.armies.items():
        if board.sanitize(name) == MT:
            continue
        out[board.sanitize(name)] = (
            Counter((u.nation.name, u.kind.name) for u in a.units),
            Counter((type(l).__name__, str(getattr(l, 'name', '')),
                     str(getattr(l, 'nation', ''))) for l in a.leaders))
    return out


def before_play():
    state = gs.setup_initial_game(board.load_board())
    gl.initialize_decks(state)
    state.hands[FP].hand = [CID]
    for name in ('fp_char_deck', 'fp_strat_deck', 'sh_char_deck', 'sh_strat_deck'):
        deck = getattr(state, name)
        if CID in deck:
            deck.remove(CID)
    first = gs.ActionDie([gs.ActionDieFace.MUSTER], FP)
    first.current = gs.ActionDieFace.MUSTER
    unused = gs.ActionDie([gs.ActionDieFace.CHARACTER], FP)
    unused.current = gs.ActionDieFace.CHARACTER
    shadow = gs.ActionDie([gs.ActionDieFace.MUSTER], SH)
    shadow.current = gs.ActionDieFace.MUSTER
    state.dice = {FP: [first, unused], SH: [shadow]}
    state.enemy_controlled = {FP: set(), SH: set()}
    return state


def exhaust_gondor_pool(state, *kinds):
    """Set permanent casualties from the physical RB7 component counts.

    No production availability helper or mutable engine cap is used as the
    oracle. All deployed copies are counted directly; the rest have died.
    """
    caps = {'regular': 15, 'elite': 5, 'leader': 4}
    dead = state.fp_casualties.setdefault(GONDOR, {})
    for kind in kinds:
        if kind == 'leader':
            deployed = sum(isinstance(l, gs.Leader) and l.nation == GONDOR
                           for a in state.armies.values() for l in a.leaders)
        else:
            wanted = REGULAR if kind == 'regular' else ELITE
            deployed = sum(u.nation == GONDOR and u.kind == wanted
                           for a in state.armies.values() for u in a.units)
        if deployed > caps[kind]:
            raise AssertionError('Fixture exceeds printed Gondor component count')
        dead[kind] = caps[kind] - deployed


def later_war(state):
    """The siege fixtures model a later, belligerent position."""
    for nation in (GONDOR, SAURON):
        state.political.active[nation] = True
        state.political.boxes[nation] = 3


class GuardsOfTheCitadelChoices(unittest.TestCase):
    def play(self, state):
        # The intended public card/die is literal. We do not select the first
        # generated action and call its own result our expected outcome.
        menu = ai.get_legal_actions(state, FP)
        self.assertTrue(any(a.action_type == 'play_event' and a.die_idx == 0
                            and a.params.get('card_id') == CID for a in menu),
                        'The printed Guards card play must be available on this Muster die')
        return ai.apply_action(state, ai.Action(0, 'play_event', {
            'card_id': CID, 'side': 'fp'}))

    def two_choices(self, state):
        pending = state.pending_card_option
        self.assertIsNotNone(pending,
                             'Both printed unit kinds require an actual pending player choice')
        self.assertEqual(pending['card_id'], CID)
        self.assertEqual(pending.get('decider', pending['side']), 'fp')
        self.assertEqual(ai._pending_decision_side(state), FP)
        menu = ai.get_legal_actions(state, FP)
        self.assertEqual(len(menu), 2, 'No decline or phantom recruit option when both kinds exist')
        self.assertEqual({a.action_type for a in menu}, {'card_option'})
        self.assertEqual({a.params.get('card_id') for a in menu}, {CID})
        self.assertEqual({(a.params.get('choices') or {}).get('unit_type')
                          for a in menu}, {'regular', 'elite'})
        return menu

    def choose(self, state, unit_type):
        menu = self.two_choices(state)
        action, = [a for a in menu
                   if a.params['choices']['unit_type'] == unit_type]
        return ai.apply_action(state, action)

    def finish_forced(self, state, expected_kind=None):
        # A unique forced outcome may be automatically executed. If the
        # implementation exposes it, it must remain exactly one outcome.
        if state.pending_card_option is not None:
            self.assertEqual(ai._pending_decision_side(state), FP)
            menu = ai.get_legal_actions(state, FP)
            self.assertEqual(len(menu), 1, 'Exhausted supply must not create a fake choice')
            if expected_kind is not None:
                self.assertEqual(menu[0].params['choices'].get('unit_type'), expected_kind)
            state = ai.apply_action(state, menu[0])
        return state

    def paid_once_and_finished(self, state):
        self.assertEqual(state.hands[FP].hand, [])
        self.assertEqual(state.discard_face_up['fp_strategy'].count(CID), 1)
        self.assertEqual([d.used for d in state.dice[FP]], [True, False])
        self.assertEqual([d.used for d in state.dice[SH]], [False])
        self.assertEqual(state.hunt_box, [])
        self.assertIsNone(state.pending_card_option)
        self.assertIsNone(state.pending_muster_die,
                          'This event is not the first half of a normal two-figure Muster')
        self.assertIsNone(state.pending_army_move_die)
        self.assertIsNone(state.pending_combat)
        self.assertIsNone(state.pending_hunt)

    def test_public_play_waits_for_fp_regular_or_elite_before_placing(self):
        state = before_play()
        self.assertEqual(gondor_figures(state), (3, 1, 1))
        self.assertFalse(state.political.active[GONDOR])
        self.assertEqual(state.political.boxes[GONDOR], 1)
        pending = self.play(state)
        self.two_choices(pending)
        self.assertEqual(gondor_figures(pending), (3, 1, 1),
                         'No Elite-first mutation before the player chooses')

    def test_each_kind_has_literal_effect_and_one_card_die_payment(self):
        for chosen, expected in [('regular', (4, 1, 2)), ('elite', (3, 2, 2))]:
            with self.subTest(unit_type=chosen):
                initial = before_play()
                others = other_armies(initial)
                politics = copy.deepcopy(initial.political)
                state = self.choose(self.play(initial), chosen)
                self.assertEqual(gondor_figures(state), expected)
                self.assertEqual(other_armies(state), others)
                self.assertEqual(state.political.boxes, politics.boxes)
                self.assertEqual(state.political.active, politics.active)
                self.paid_once_and_finished(state)

    def test_actual_legal_unit_choices_have_different_encodings(self):
        state = self.play(before_play())
        menu = self.two_choices(state)
        vectors = [ai.encode_action(a, state, FP) for a in menu]
        self.assertNotEqual(vectors[0].tobytes(), vectors[1].tobytes(),
                            'The policy must distinguish the printed Regular and Elite alternatives')
        self.assertEqual({len(v) for v in vectors}, {ai.ACTION_ENCODING_DIM})

    def test_prospective_unit_type_encodings_do_not_collapse(self):
        # This isolates encoding even before menu exposure is implemented.
        state = before_play()
        vectors = [ai.encode_action(ai.Action(-1, 'card_option', {
            'card_id': CID, 'side': 'fp', 'card_name': TITLE,
            'choices': {'unit_type': kind}}), state, FP)
            for kind in ('regular', 'elite')]
        self.assertNotEqual(vectors[0].tobytes(), vectors[1].tobytes(),
                            'Adding ignored unit_type dictionaries is not a learning implementation')
        self.assertAlmostEqual(float(vectors[0][ai._ACT_OPTKIND_OFF]), 0.34)
        self.assertAlmostEqual(float(vectors[1][ai._ACT_OPTKIND_OFF]), 0.67)
        self.assertEqual({i for i, (left, right) in enumerate(zip(*vectors))
                          if left != right}, {ai._ACT_OPTKIND_OFF})

    def test_invalid_choice_rejects_before_mutating_the_paid_pending(self):
        for invalid in ({}, {'unit_type': 'leader'}, {'unit_type': None},
                        {'unit_type': 'regular', 'recruit_count': 0}):
            with self.subTest(choices=invalid):
                state = self.play(before_play())
                self.two_choices(state)
                pending = state.pending_card_option
                hand = list(state.hands[FP].hand)
                discards = copy.deepcopy(state.discard_face_up)
                bad = ai.Action(-1, 'card_option', {
                    'card_id': CID, 'side': 'fp', 'choices': invalid})
                # In-place execution matters: a clone-only test could hide
                # clearing a pending before rejecting a malformed choice.
                with self.assertRaises((ValueError, RuntimeError)):
                    ai._execute_action(state, bad)
                self.assertIs(state.pending_card_option, pending)
                self.assertEqual(gondor_figures(state), (3, 1, 1))
                self.assertEqual(state.hands[FP].hand, hand)
                self.assertEqual(state.discard_face_up, discards)
                self.assertEqual([d.used for d in state.dice[FP]], [True, False])
                self.assertEqual([d.used for d in state.dice[SH]], [False])

    def test_choice_with_now_exhausted_supply_rejects_before_losing_pending(self):
        state = self.play(before_play())
        menu = self.two_choices(state)
        regular, = [a for a in menu if a.params['choices']['unit_type'] == 'regular']
        # A stale external request is not a legal invitation to omit the
        # unit and keep only the Leader while an Elite remains available.
        exhaust_gondor_pool(state, 'regular')
        pending = state.pending_card_option
        with self.assertRaises((ValueError, RuntimeError)):
            ai._execute_action(state, regular)
        self.assertIs(state.pending_card_option, pending)
        self.assertEqual(gondor_figures(state), (3, 1, 1))
        self.assertIn(CID, state.hands[FP].hand)
        self.assertEqual([d.used for d in state.dice[FP]], [True, False])

    def test_invalid_explicit_play_rejects_before_spending_its_die_or_card(self):
        for choices, exhausted in [({'unit_type': 'leader'}, None),
                                   ({'unit_type': 'regular'}, 'regular')]:
            with self.subTest(choices=choices, exhausted=exhausted):
                state = before_play()
                if exhausted:
                    exhaust_gondor_pool(state, exhausted)
                action = ai.Action(0, 'play_event', {
                    'card_id': CID, 'side': 'fp', 'choices': choices})
                with self.assertRaises((ValueError, RuntimeError)):
                    ai._execute_action(state, action)
                self.assertEqual(gondor_figures(state), (3, 1, 1))
                self.assertEqual(state.hands[FP].hand, [CID])
                self.assertNotIn(CID, state.discard_face_up['fp_strategy'])
                self.assertEqual([d.used for d in state.dice[FP]], [False, False])
                self.assertIsNone(getattr(state, 'pending_card_option', None))

    def test_exhausted_regular_pool_forces_elite_plus_leader(self):
        initial = before_play()
        exhaust_gondor_pool(initial, 'regular')
        state = self.finish_forced(self.play(initial), 'elite')
        self.assertEqual(gondor_figures(state), (3, 2, 2))
        self.paid_once_and_finished(state)

    def test_exhausted_elite_pool_forces_regular_plus_leader(self):
        initial = before_play()
        exhaust_gondor_pool(initial, 'elite')
        state = self.finish_forced(self.play(initial), 'regular')
        self.assertEqual(gondor_figures(state), (4, 1, 2))
        self.paid_once_and_finished(state)

    def test_no_unit_supply_still_compulsorily_places_available_leader(self):
        initial = before_play()
        exhaust_gondor_pool(initial, 'regular', 'elite')
        state = self.finish_forced(self.play(initial))
        self.assertEqual(gondor_figures(state), (3, 1, 2))
        self.paid_once_and_finished(state)

    def test_no_leader_supply_preserves_both_compulsory_unit_alternatives(self):
        for chosen, expected in [('regular', (4, 1, 1)), ('elite', (3, 2, 1))]:
            with self.subTest(unit_type=chosen):
                initial = before_play()
                exhaust_gondor_pool(initial, 'leader')
                state = self.choose(self.play(initial), chosen)
                self.assertEqual(gondor_figures(state), expected)
                self.paid_once_and_finished(state)

    def test_all_supplies_exhausted_completes_without_phantom_choice(self):
        initial = before_play()
        exhaust_gondor_pool(initial, 'regular', 'elite', 'leader')
        state = self.finish_forced(self.play(initial))
        self.assertEqual(gondor_figures(state), (3, 1, 1))
        self.paid_once_and_finished(state)

    def test_empty_friendly_minas_tirith_can_receive_chosen_unit_and_leader(self):
        for chosen, expected in [('regular', (1, 0, 1)), ('elite', (0, 1, 1))]:
            with self.subTest(unit_type=chosen):
                initial = before_play()
                # A prior legal army move can leave the friendly stronghold
                # empty; preserve the original pieces in Lossarnach.
                source = army(initial)
                destination = gl.get_or_create_army(initial, 'Lossarnach')
                destination.units.extend(source.units)
                destination.leaders.extend(source.leaders)
                source.units = []
                source.leaders = []
                state = self.choose(self.play(initial), chosen)
                self.assertEqual(gondor_figures(state), expected)
                self.paid_once_and_finished(state)

    def test_fp_besieged_garrison_gets_both_choices_at_cap_minus_one(self):
        for chosen, expected in [('regular', (4, 1, 2)), ('elite', (3, 2, 2))]:
            with self.subTest(unit_type=chosen):
                initial = before_play()
                later_war(initial)
                army(initial).units.extend([gs.Unit(SAURON, REGULAR) for _ in range(2)])
                initial.besieged_strongholds.add(MT)
                state = self.choose(self.play(initial), chosen)
                self.assertEqual(gondor_figures(state), expected)
                self.assertEqual(sum(u.nation == SAURON for u in army(state).units), 2)
                self.assertIn(MT, state.besieged_strongholds)
                self.assertNotIn(MT, state.enemy_controlled[SH])
                self.paid_once_and_finished(state)

    def test_fp_besieger_of_captured_minas_tirith_can_recruit_both_kinds(self):
        for chosen, expected in [('regular', (4, 1, 2)), ('elite', (3, 2, 2))]:
            with self.subTest(unit_type=chosen):
                initial = before_play()
                later_war(initial)
                army(initial).units.extend([gs.Unit(SAURON, REGULAR) for _ in range(2)])
                initial.enemy_controlled[SH].add(MT)
                initial.besieged_strongholds.add(MT)
                state = self.choose(self.play(initial), chosen)
                self.assertEqual(gondor_figures(state), expected)
                self.assertIn(MT, state.enemy_controlled[SH],
                              'Reinforcing the besieger does not capture the stronghold')
                self.assertEqual(sum(u.nation == SAURON for u in army(state).units), 2)
                self.paid_once_and_finished(state)

    def test_captured_minas_tirith_without_fp_besieger_cannot_receive_figures(self):
        for shadow_regulars in (0, 2):
            with self.subTest(shadow_garrison=shadow_regulars):
                initial = before_play()
                later_war(initial)
                # The original MT garrison was eliminated before capture.
                initial.fp_casualties[GONDOR] = {'regular': 3, 'elite': 1, 'leader': 1}
                army(initial).units = [gs.Unit(SAURON, REGULAR)
                                       for _ in range(shadow_regulars)]
                army(initial).leaders = []
                initial.enemy_controlled[SH].add(MT)
                state = self.finish_forced(self.play(initial))
                self.assertEqual(gondor_figures(state), (0, 0, 0))
                self.assertIn(MT, state.enemy_controlled[SH])
                self.paid_once_and_finished(state)

    def test_maximum_placement_precedes_owner_overstack_return(self):
        # AL22's explicit Guards example: FP besieges captured MT with ten
        # Regulars; recruit an Elite + Leader, then return a Regular. Merely
        # declining the recruit at cap ten would suppress a useful exchange.
        initial = before_play()
        initial.armies.clear()
        later_war(initial)
        a = gl.get_or_create_army(initial, 'Minas Tirith')
        a.units = ([gs.Unit(GONDOR, REGULAR) for _ in range(10)]
                   + [gs.Unit(SAURON, REGULAR) for _ in range(2)])
        initial.enemy_controlled[SH].add(MT)
        initial.besieged_strongholds.add(MT)
        prior_casualties = copy.deepcopy(initial.fp_casualties)
        state = self.choose(self.play(initial), 'elite')
        self.assertEqual(gondor_figures(state), (10, 1, 1))
        self.assertIsNotNone(state.pending_card_option)
        self.assertEqual(state.pending_card_option['card_name'], '__overstack__')
        self.assertEqual(ai._pending_decision_side(state), FP)
        removals = [a for a in ai.get_legal_actions(state, FP)
                    if (a.params.get('choices') or {}).get('overstack_remove', {}).get('kind')
                    == 'regular']
        self.assertEqual(len(removals), 1)
        state = ai.apply_action(state, removals[0])
        self.assertEqual(gondor_figures(state), (9, 1, 1))
        self.assertEqual(state.fp_casualties, prior_casualties,
                         'Overstack goes to reinforcements, not permanent casualties')
        self.assertIn(MT, state.enemy_controlled[SH])
        self.assertEqual(sum(u.nation == SAURON for u in army(state).units), 2)
        self.paid_once_and_finished(state)


if __name__ == '__main__':
    unittest.main(verbosity=2)

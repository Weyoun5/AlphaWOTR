"""Native late reveal of a previous battle's publicly committed card.

Rulebook PDF29: effects normally last one round; discard at round end.
The fpgame15 journal establishes Paths was used in Woodland, then its
physical chooser/reveal arrived at Lorien. This is a bounded later-position
driver test, not a complete replay or Java test. Human records are captured,
not generated by the engine/emitter; expected hands and decision are literal.
"""
import json
import os
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'src'), str(ROOT / 'wotr_bridge'), str(ROOT)]
os.environ.setdefault('CUDA_VISIBLE_DEVICES', '-1')
import ai
import board
import game_logic as gl
import game_state as gs
from live.driver import DriverHalt, LiveDriver
from live.randomness import ClientRandomness, NeedClientCall

FP, SH = gs.Side.FREE_PEOPLES, gs.Side.SHADOW
PATHS = 'FREE_PEOPLES_Strategy_Paths_of_the_Woses'
LAST = 'FREE_PEOPLES_Strategy_The_Last_Battle'
BALROG = 'SHADOW_Character_Balrog_of_Moria'
CAPTURE = json.loads((ROOT / 'wotr_bridge/tests/fixtures/fpgame15_late_cc_20260905/capture.json').read_text())
CHOOSE, REVEAL = [row['text'] for row in CAPTURE['lines']]
NEW_REVEAL = '<auto> moves The Last Battle/Daylight from Free Peoples Hand (chosen) to Current FP Card.'


def prior_position():
    state = gs.setup_initial_game(board.load_board())
    gl.initialize_decks(state)
    def army(name):
        return next(a for k, a in state.armies.items() if board.sanitize(k) == name)
    target, donor = army('lorien'), army('dol guldur')
    target.units.extend(donor.units)
    donor.units = []
    target.leaders.extend(donor.leaders)
    donor.leaders = []
    for name, count, kind in [('barad dur', 2, gs.UnitKind.REGULAR), ('orthanc', 1, gs.UnitKind.ELITE)]:
        donor = army(name)
        for _ in range(count):
            unit = next(u for u in donor.units if u.kind == kind)
            donor.units.remove(unit)
            target.units.append(unit)
    state.besieged_strongholds = {'lorien'}
    for nation in (gs.Nation.ELVES, gs.Nation.SAURON, gs.Nation.ISENGARD):
        state.political.boxes[nation] = 3
        state.political.active[nation] = True
    state.hands[FP].hand = [LAST]
    state.hands[SH].hand = [BALROG]
    state.fp_strat_deck.remove(PATHS)
    state.fp_strat_deck.remove(LAST)
    state.sh_char_deck.remove(BALROG)
    state.discard_face_up = {'fp_strategy': [PATHS]}
    gl.adopt_rolled_faces(state, [(SH, 0, gs.ActionDieFace.ARMY)])
    return state


class LateCombatRevealTests(unittest.TestCase):
    def rig(self):
        temp = tempfile.TemporaryDirectory(prefix='wotr-late-cc-test-')
        self.addCleanup(temp.cleanup)
        feed = Path(temp.name) / 'feed.txt'
        feed.write_text('')
        rand = ClientRandomness(seed=7)
        rand.install()
        drv = LiveDriver(prior_position(), SH, str(feed), randomness=rand, nick='WOTR_AI_Shadow')
        drv.phase = 'actions'
        # Recorded prior public commitment is already resolved in the engine,
        # but its exact card still has an outstanding physical reveal.
        drv._cc_reveal_owed = {PATHS: 'owed'}
        for action in [ai.Action(0, 'army_attack', {'from': 'lorien', 'to': 'lorien', 'side': 'sh'}),
                       ai.Action(-1, 'siege_assault', {}),
                       ai.Action(-1, 'combat_card_play', {'card_id': BALROG, 'side': 'sh'})]:
            pre = drv.es
            post = ai.apply_action(pre, action)
            drv.es = post
            for hm in drv.hand_models.values():
                hm.es = post
            drv.hands.es = post
            drv.post_commit_sweep(pre, post, label='ai:' + action.action_type)
        self.assertEqual(drv.es.pending_combat['phase'], 'defender_combat_card')
        return drv, feed, rand

    @staticmethod
    def feed(drv, path, *lines):
        with path.open('a', encoding='utf-8') as stream:
            stream.write('\n'.join(lines) + '\n')
        return drv.tick()

    def assert_old_reveal_only(self, drv, rand):
        self.assertEqual(drv.es.hands[FP].hand, [LAST])
        self.assertEqual(drv.es.discard_face_up['fp_strategy'], [PATHS])
        self.assertEqual(drv.es.pending_combat['phase'], 'defender_combat_card')
        self.assertEqual(drv.es.pending_combat['atk_combat_card'], BALROG)
        self.assertNotIn('def_hidden_cc', drv.es.pending_combat)
        self.assertFalse(drv.human_cc_committed)
        self.assertIsNone(drv.chat_deferred)
        self.assertFalse(any(rand.unconsumed().values()))
        self.assertEqual(drv.alarms, [])
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'claimed')

    def test_new_battle_keeps_exact_unresolved_old_reveal(self):
        drv, _, _ = self.rig()
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'owed')

    def test_grouped_archived_preamble_and_reveal_leave_new_choice_open(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE, REVEAL)
        self.assert_old_reveal_only(drv, rand)

    def test_split_archived_preamble_idle_then_reveal_leave_new_choice_open(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE)
        self.assertTrue(drv.human_cc_committed, 'A real new chooser must still be able to commit')
        for _ in range(3):
            drv.tick()
        self.feed(drv, path, REVEAL)
        self.assert_old_reveal_only(drv, rand)

    def test_duplicate_preamble_reveal_and_idle_cannot_commit_old_card_again(self):
        drv, path, rand = self.rig()
        for _ in range(2):
            self.feed(drv, path, CHOOSE, REVEAL)
            self.assert_old_reveal_only(drv, rand)
        self.feed(drv, path, REVEAL)
        for _ in range(3):
            drv.tick()
        self.assert_old_reveal_only(drv, rand)

    def test_different_held_card_remains_a_real_current_commit(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE, NEW_REVEAL)
        self.assertIsNotNone(drv.chat_deferred, 'Current reveal should reach its real combat RNG request')
        self.assertEqual(drv.chat_deferred[1], 'cc_reveal')
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'owed')
        self.assertEqual(drv.es.hands[FP].hand, [LAST], 'Starved reveal remains transactional')
        self.assertEqual(drv.es.discard_face_up['fp_strategy'], [PATHS])
        self.assertTrue(any(k == 'cc_reveal' and LAST in str(v) for k, v in drv.findings))
        self.assertEqual(drv.alarms, [])

    def test_old_reveal_without_its_preamble_preserves_existing_hidden_choice(self):
        drv, path, rand = self.rig()
        def commit(state):
            ai.commit_hidden_combat_card(state, FP, 'strategy')
        commit.action_type = 'combat_card_hidden_commit'
        drv._attempt_chat_action(commit, via='explicit-test-current-commit')
        self.feed(drv, path, REVEAL)
        self.assertTrue(drv.human_cc_committed)
        self.assertIn('def_hidden_cc', drv.es.pending_combat)
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'claimed')
        self.assertEqual(drv.es.hands[FP].hand, [LAST])
        self.assertFalse(any(rand.unconsumed().values()))

    def test_extra_chooser_during_existing_commit_does_not_withdraw_it(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE)
        self.feed(drv, path, CHOOSE, REVEAL)
        self.assertTrue(drv.human_cc_committed)
        self.assertIn('def_hidden_cc', drv.es.pending_combat)
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'claimed')
        self.feed(drv, path, NEW_REVEAL)
        self.assertIsNotNone(drv.chat_deferred)
        self.assertEqual(drv.chat_deferred[1], 'cc_reveal')
        self.assertEqual(drv.alarms, [])

    def test_ai_choose_echo_between_old_preamble_and_reveal_is_harmless(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE)
        self.feed(drv, path, '$WOTR_AI_Shadow chooses a card.[Shadow Character Card]')
        self.feed(drv, path, REVEAL)
        self.assert_old_reveal_only(drv, rand)

    def test_unknown_old_identity_cannot_claim_a_current_card(self):
        drv, path, rand = self.rig()
        drv._cc_reveal_owed = {'*': 'owed'}
        drv._cc_reveal_origins = {'*': drv._cc_battle_serial - 1}
        self.feed(drv, path, CHOOSE, NEW_REVEAL)
        self.assertEqual(drv._cc_reveal_owed, {'*': 'owed'})
        self.assertIsNotNone(drv.chat_deferred)
        self.assertEqual(drv.chat_deferred[1], 'cc_reveal')
        self.assertFalse(any(k == 'cc_prior_reveal' for k, _ in drv.findings))
        self.assertEqual(drv.alarms, [])

    def test_different_deck_preamble_does_not_cancel_current_choice(self):
        drv, path, rand = self.rig()
        athelas = 'FREE_PEOPLES_Character_Athelas'
        drv.es.hands[FP].hand.append(athelas)
        drv.es.fp_char_deck.remove(athelas)
        self.feed(drv, path, '$Wey chooses a card.[Free Character Card]')
        self.feed(drv, path, REVEAL)
        self.assertEqual(drv.es.pending_combat['def_hidden_cc'], {'deck': 'character'})
        self.assertTrue(drv.human_cc_committed)
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'claimed')
        self.assertEqual(drv.es.hands[FP].hand, [LAST, athelas])
        self.assertFalse(any(rand.unconsumed().values()))
        self.assertEqual(drv.alarms, [])

    def test_unrelated_unheld_card_does_not_satisfy_old_obligation(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE,
                  '<auto> moves Book of Mazarbul/Advantageous Position from Free Peoples Hand (chosen) to Current FP Card.')
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'owed')
        self.assertEqual(drv.es.hands[FP].hand, [LAST])
        self.assertEqual(drv.es.discard_face_up['fp_strategy'], [PATHS])
        self.assertTrue(any('COMBAT CARD REVEAL' in alarm for alarm in drv.alarms))
        self.assertFalse(any(k == 'cc_prior_reveal' for k, _ in drv.findings))

    def test_failed_cancellation_preserves_exact_retry_identity_and_epoch(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE)
        preamble, epoch = drv._cc_choose_preamble, drv.cc_reveal_epoch
        with patch.object(ai, 'cancel_hidden_combat_card', side_effect=RuntimeError('injected cancellation failure')):
            with self.assertRaises(DriverHalt):
                drv._claim_cc_reveal('Paths of the Woses/Sudden Strike')
        self.assertEqual(drv._cc_choose_preamble, preamble)
        self.assertEqual(drv.cc_reveal_epoch, epoch)
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'owed')
        self.assertTrue(drv.human_cc_committed)
        self.feed(drv, path, REVEAL)
        self.assert_old_reveal_only(drv, rand)

    def test_unexpected_randomness_cannot_mark_cancellation_complete(self):
        drv, path, rand = self.rig()
        self.feed(drv, path, CHOOSE)
        preamble, epoch = drv._cc_choose_preamble, drv.cc_reveal_epoch
        with patch.object(ai, 'cancel_hidden_combat_card', side_effect=NeedClientCall('d6', need=1)):
            with self.assertRaises(DriverHalt):
                drv._claim_cc_reveal('Paths of the Woses/Sudden Strike')
        self.assertEqual(drv._cc_choose_preamble, preamble)
        self.assertEqual(drv.cc_reveal_epoch, epoch)
        self.assertEqual(drv._cc_reveal_owed.get(PATHS), 'owed')
        self.assertTrue(drv.human_cc_committed)
        self.assertIsNone(drv.chat_deferred, 'An impossible cancellation deferral must not retry as ordinary gameplay')
        self.feed(drv, path, REVEAL)
        self.assert_old_reveal_only(drv, rand)


if __name__ == '__main__':
    unittest.main()

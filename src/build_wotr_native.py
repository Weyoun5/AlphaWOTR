"""Build WOTR native extensions with explicit provenance.

Verified candidate build, without changing the live extension:
  python src/build_wotr_native.py --generate-candidate PATH
  python src/build_wotr_native.py --generate-candidate PATH --source-root ENGINE

The candidate command copies an immutable source/data snapshot, generates the
mirrors directly from Python, compiles with setuptools' platform compiler,
and checks standalone board import, actual native activation and independent
Python/native observations and public action encodings. PATH must be new.
The full manifest and logs remain there. This command does not activate or
publish the candidate. Cython and a working native C compiler are required.

Calling without arguments retains the legacy checked-mirror build. It refuses
missing or stale handwritten provenance before changing files; it never stamps
current identity onto an old transcription. Prefer the generated candidate
command when Python source has changed.
"""
import glob
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PYX = os.path.join(HERE, 'wotr_native.pyx')

# The five mirrored hot paths: the pyd may only activate against the
# EXACT Python sources it was transcribed from.  Order is part of the
# hash contract -- never reorder.
MIRROR_FUNCS = ('clone_state', 'encode_state', '_state_sig',
                'encode_action', '_action_cache_key')
FP_BEGIN = ('# MIRROR-FP-BEGIN (generated by build_wotr_native.py '
            '-- do not edit)')
FP_END = '# MIRROR-FP-END'


def mirror_fingerprint(ai_module=None):
    """sha1 over the concatenated inspect.getsource of MIRROR_FUNCS,
    in declared order.  The ONE implementation for both sides of the
    contract: the build bakes the result into the pyd and the ai.py
    WOTR_NATIVE guard calls this with its own module (BEFORE the
    rebind statements) to compare.  Loud failure when a function is
    missing or its source is unavailable -- never a silent skip."""
    import hashlib
    import inspect
    if ai_module is None:
        if os.environ.get('WOTR_NATIVE') == '1':
            raise SystemExit(
                'mirror_fingerprint: refusing to fingerprint with '
                'WOTR_NATIVE=1 in the environment -- the sources '
                'would be the pyd rebinds, not ai.py')
        os.environ.setdefault('KMP_DUPLICATE_LIB_OK', 'TRUE')
        os.environ.setdefault('CUDA_VISIBLE_DEVICES', '-1')
        if HERE not in sys.path:
            sys.path.insert(0, HERE)
        import ai as ai_module
    h = hashlib.sha1()
    for name in MIRROR_FUNCS:
        fn = getattr(ai_module, name, None)
        if fn is None:
            raise RuntimeError(
                'mirror_fingerprint: %s.%s missing -- cannot '
                'fingerprint the mirror set'
                % (getattr(ai_module, '__name__', '?'), name))
        try:
            src = inspect.getsource(fn)
        except (OSError, TypeError) as e:
            raise RuntimeError(
                'mirror_fingerprint: source of %s.%s unavailable '
                '(%r) -- native rebinds active in this process?'
                % (getattr(ai_module, '__name__', '?'), name, e))
        h.update(src.encode('utf-8'))
    return h.hexdigest()


def inject_fingerprint(pyx_path, fp):
    """Low-level generation helper; not a certificate of mirror parity.

    Bake `MIRROR_FINGERPRINT = '<sha1>'` into the pyx as a
    marker-delimited block at EOF (replaced on every build, never
    duplicated; CRLF and the cython directive header preserved;
    ASCII only; atomic write)."""
    with open(pyx_path, 'r', encoding='ascii') as f:
        lines = f.read().split('\n')
    out, skip = [], False
    for ln in lines:
        if ln.strip() == FP_BEGIN:
            skip = True
            continue
        if skip:
            if ln.strip() == FP_END:
                skip = False
            continue
        out.append(ln)
    while out and not out[-1].strip():
        out.pop()
    out += ['', '', FP_BEGIN,
            "MIRROR_FINGERPRINT = '%s'" % fp, FP_END, '']
    tmp = pyx_path + '.tmp'
    with open(tmp, 'w', encoding='ascii', newline='\r\n') as f:
        f.write('\n'.join(out))
    os.replace(tmp, pyx_path)


def require_mirror_provenance(pyx_path, expected):
    """Check the existing declaration without blessing or rewriting its body."""
    with open(pyx_path, 'r', encoding='ascii') as handle:
        lines = handle.read().splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == FP_BEGIN]
    ends = [i for i, line in enumerate(lines) if line.strip() == FP_END]
    declared = None
    if len(starts) == len(ends) == 1 and ends[0] == starts[0] + 2:
        match = re.fullmatch(r"MIRROR_FINGERPRINT = '([0-9a-f]{40})'",
                             lines[starts[0] + 1].strip())
        if match:
            declared = match.group(1)
    if declared != expected:
        raise SystemExit(
            'native mirror provenance is missing, malformed, or stale; '
            'refusing to restamp an old implementation. Regenerate or review '
            'the mirror and validate parity before rebuilding. No files changed.')
    return declared


def _check_build_dir(build_dir):
    """Refuse-if-unexpected guard (USER 2026-08-22 no-destructive-
    patterns: never rmtree a variable path unchecked) -- only
    <src>\\build_native may be recursively deleted."""
    if (os.path.basename(build_dir) != 'build_native'
            or os.path.abspath(os.path.dirname(build_dir))
            != os.path.abspath(HERE)):
        raise SystemExit('refusing rmtree of unexpected dir: %r'
                         % (build_dir,))


def _legacy_main():
    fp = mirror_fingerprint()
    require_mirror_provenance(PYX, fp)
    import Cython
    import numpy
    import setuptools
    print('MIRROR_FINGERPRINT %s matches existing mirror declaration' % fp)
    build_dir = os.path.join(HERE, 'build_native')
    _check_build_dir(build_dir)
    if os.path.isdir(build_dir):
        shutil.rmtree(build_dir)
    for f in glob.glob(os.path.join(HERE, 'wotr_native*.pyd')):
        os.remove(f)
    rc = subprocess.call([
        sys.executable, '-c',
        "from setuptools import setup;"
        "from Cython.Build import cythonize;"
        "setup(name='wotr_native',"
        " ext_modules=cythonize(['wotr_native.pyx'], language_level=3,"
        " build_dir='build_native'),"
        " script_args=['build_ext', '--inplace',"
        " '--build-temp', 'build_native'])",
    ], cwd=HERE)
    if rc != 0:
        print('BUILD FAILED rc=%d' % rc)
        sys.exit(rc)
    pyds = glob.glob(os.path.join(HERE, 'wotr_native*.pyd'))
    if len(pyds) != 1:
        print('expected exactly one built pyd, found: %r' % (pyds,))
        sys.exit(2)
    with open(os.path.join(HERE, 'build_info_native.txt'), 'w') as f:
        f.write('python %s\n' % sys.version.replace('\n', ' '))
        f.write('cython %s\n' % Cython.__version__)
        f.write('numpy %s\n' % numpy.__version__)
        f.write('setuptools %s\n' % setuptools.__version__)
        f.write('pyd %s\n' % os.path.basename(pyds[0]))
        # staleness forensics (SPLP-1: the old build info recorded no
        # source identity at all)
        f.write('mirror_fingerprint %s\n' % fp)
    print('OK: built %s (MIRROR_FINGERPRINT %s)' % (pyds[0], fp))


def build_generated_candidate(source_root, output_dir, action_generation="v41"):
    from pathlib import Path
    from native_build_candidate import build_candidate
    return build_candidate(Path(source_root), Path(output_dir), Path(HERE), action_generation=action_generation)


def main(argv=()):
    if not argv:
        return _legacy_main()
    import argparse
    parser = argparse.ArgumentParser(description='Build a verified private source-generated native candidate; live artifacts stay unchanged.')
    parser.add_argument('--generate-candidate', required=True, type=str, metavar='OUTPUT_DIRECTORY')
    parser.add_argument('--source-root', default=os.path.dirname(HERE))
    parser.add_argument("--action-generation", choices=("v41", "v45", "v46", "v47", "v48", "v49", "v50", "v51", "v52"), default="v41")
    args = parser.parse_args(argv)
    return build_generated_candidate(args.source_root, args.generate_candidate, args.action_generation)


if __name__ == '__main__':
    main(sys.argv[1:])

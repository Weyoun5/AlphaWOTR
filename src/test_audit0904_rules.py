"""Independent rulebook/almanac acceptance examples, 2026-09-04.

Run with Python's unittest; no pytest dependency. Expectations below are
authored from the cited printed rules, never generated by the rules engine.
PDF page numbers also match audit/2026-09-04/reference page markers.
"""
import unittest
from unittest.mock import patch

import board
import card_options
import cards
import combat
import game_logic as gl
import game_state as gs
from persistent_effects import create_persistent_card

FP, SH = gs.Side.FREE_PEOPLES, gs.Side.SHADOW
R = gs.UnitKind.REGULAR


def fresh():
    state = gs.setup_initial_game(board.load_board())
    gl.initialize_decks(state)
    state.armies.clear()
    state.enemy_controlled = {FP: set(), SH: set()}
    return state


def place(state, region, nation, count):
    army = gl.get_or_create_army(state, region)
    army.units = [gs.Unit(nation, R) for _ in range(count)]
    return army


def dice(state, side, face):
    die = gs.ActionDie([face], side)
    die.current = face
    state.dice[side] = [die]


def wormtongue(state, position=1):
    # Keep Saruman physically present so normal post-action cleanup is valid.
    state.saruman.in_play = True
    gl.get_or_create_army(state, 'orthanc').leaders.append(
        gl.Minion(gs.Nation.ISENGARD, 'Saruman'))
    state.persistent_cards.add_card(create_persistent_card(
        'SHADOW_Character_Wormtongue', 'Wormtongue', SH))
    state.political.active[gs.Nation.ROHAN] = False
    state.political.boxes[gs.Nation.ROHAN] = position


class CaptureRules(unittest.TestCase):
    def test_whole_army_entry_captures_empty_city_immediately(self):
        """Rulebook p32: enemy entry captures a City, including whole armies."""
        state = fresh()
        place(state, 'west harondor', gs.Nation.SAURON, 2)
        state.political.active[gs.Nation.GONDOR] = False
        state.political.boxes[gs.Nation.GONDOR] = 1
        gl.move_army(state, 'west harondor', 'pelargir', side=SH)
        self.assertEqual(state.enemy_controlled[SH], {'pelargir'})
        self.assertTrue(state.political.active[gs.Nation.GONDOR])
        self.assertEqual(state.political.boxes[gs.Nation.GONDOR], 2)
        self.assertEqual(gl.calculate_victory_points(state)['shadow'], 1)

    def test_split_army_entry_captures_empty_city_once(self):
        """Rulebook p32/34: one capture gives one political advance."""
        state = fresh()
        place(state, 'west harondor', gs.Nation.SAURON, 3)
        state.political.boxes[gs.Nation.GONDOR] = 1
        gl.move_army(state, 'west harondor', 'pelargir', side=SH,
                     move_units=1, move_elite=0, move_leaders=0)
        self.assertEqual(state.enemy_controlled[SH], {'pelargir'})
        self.assertEqual(state.political.boxes[gs.Nation.GONDOR], 2)
        gl.move_army(state, 'west harondor', 'pelargir', side=SH)
        self.assertEqual(state.political.boxes[gs.Nation.GONDOR], 2)

    def test_recapture_removes_enemy_vp_without_political_advance(self):
        """Rulebook p32: retaking one's city removes the conquest marker."""
        state = fresh()
        place(state, 'west harondor', gs.Nation.GONDOR, 2)
        state.enemy_controlled[SH].add('pelargir')
        state.political.boxes[gs.Nation.GONDOR] = 1
        gl.move_army(state, 'west harondor', 'pelargir', side=FP)
        self.assertEqual(state.enemy_controlled[SH], set())
        self.assertEqual(state.enemy_controlled[FP], set())
        self.assertEqual(state.political.boxes[gs.Nation.GONDOR], 1)
        self.assertEqual(gl.calculate_victory_points(state)['shadow'], 0)

    def test_wormtongue_empty_city_entry_is_not_an_attack(self):
        """Almanac p29, SH C22: empty Edoras entry leaves Rohan passive."""
        import ai
        state = fresh()
        wormtongue(state)
        place(state, 'westemnet', gs.Nation.ISENGARD, 2)
        state.political.boxes[gs.Nation.ISENGARD] = 3
        dice(state, SH, gs.ActionDieFace.ARMY)
        # Fixed player intention, not the first action returned by a generator.
        ai._execute_action(state, ai.Action(0, 'army_move', {
            'from': 'westemnet', 'to': 'edoras', 'side': 'sh'}))
        self.assertEqual(state.enemy_controlled[SH], {'edoras'})
        self.assertFalse(state.political.active[gs.Nation.ROHAN])
        self.assertEqual(state.political.boxes[gs.Nation.ROHAN], 2)
        self.assertTrue(state.persistent_cards.has_card('Wormtongue'))

    def test_wormtongue_empty_stronghold_entry_cannot_reach_at_war(self):
        """Almanac p29, SH C22: unopposed Helm's Deep entry is movement."""
        state = fresh()
        wormtongue(state, position=2)
        place(state, 'westemnet', gs.Nation.ISENGARD, 2)
        gl.move_army(state, 'westemnet', "helm's deep", side=SH,
                     move_units=1, move_elite=0, move_leaders=0)
        self.assertIn('helm s deep', state.enemy_controlled[SH])
        self.assertFalse(state.political.active[gs.Nation.ROHAN])
        self.assertEqual(state.political.boxes[gs.Nation.ROHAN], 2)
        self.assertTrue(state.persistent_cards.has_card('Wormtongue'))

    def test_wormtongue_capture_notification_does_not_imply_attack(self):
        """Almanac p29: capture-only callers must preserve Wormtongue."""
        state = fresh()
        wormtongue(state)
        gl.activate_nation_for_attack(state, 'edoras', captured=True)
        self.assertFalse(state.political.active[gs.Nation.ROHAN])
        self.assertEqual(state.political.boxes[gs.Nation.ROHAN], 2)
        self.assertTrue(state.persistent_cards.has_card('Wormtongue'))

    def test_wormtongue_actual_attack_on_edoras_activates_rohan(self):
        """Almanac p29: an actual attack is the explicitly allowed exception."""
        state = fresh()
        wormtongue(state, position=2)
        gl.activate_nation_for_attack(state, 'edoras', attacked=True)
        self.assertTrue(state.political.active[gs.Nation.ROHAN])
        self.assertEqual(state.political.boxes[gs.Nation.ROHAN], 3)
        self.assertFalse(state.persistent_cards.has_card('Wormtongue'))


class AlmanacInteractions(unittest.TestCase):
    def test_threats_and_promises_survives_blocked_rohan_attack(self):
        """Almanac p32, SH S5: attack with no advance does not discard it."""
        state = fresh()
        wormtongue(state, position=2)
        state.persistent_cards.add_card(create_persistent_card(
            'SHADOW_Strategy_Threats_and_Promises', 'Threats and Promises', SH))
        gl.activate_nation_for_attack(state, 'westemnet', attacked=True)
        self.assertEqual(state.political.boxes[gs.Nation.ROHAN], 2)
        self.assertTrue(state.persistent_cards.has_card('Threats and Promises'))
        gl.activate_nation_for_attack(state, 'edoras', attacked=True)
        self.assertEqual(state.political.boxes[gs.Nation.ROHAN], 3)
        self.assertFalse(state.persistent_cards.has_card('Threats and Promises'))

    def test_fellowship_members_do_not_satisfy_combat_character_requirement(self):
        """Rulebook p35/36; Almanac p3: Fellowship companions are not in battle."""
        state = fresh()
        place(state, 'west harondor', gs.Nation.SAURON, 2)
        fp_army = place(state, 'pelargir', gs.Nation.GONDOR, 2)
        gandalf = next(c for c in state.fellowship.companions
                       if c.name == 'Gandalf the Grey')
        staff = cards.get_card("FREE_PEOPLES_Character_Wizard's_Staff")
        battle = combat.setup_combat(state, 'west harondor', 'pelargir')
        self.assertFalse(cards.can_play_combat_card(staff, battle, False, state)[0])
        state.fellowship.companions.remove(gandalf)
        fp_army.leaders.append(gandalf)
        battle = combat.setup_combat(state, 'west harondor', 'pelargir')
        self.assertTrue(cards.can_play_combat_card(staff, battle, False, state)[0])

    def test_final_mordor_step_waits_for_damage_and_corruption_has_priority(self):
        """Rulebook p43/44: finish the final Hunt before declaring Ring victory."""
        state = fresh()
        state.fellowship.mordor_entered = True
        state.fellowship.mordor_step = 5
        state.fellowship.corruption = 11
        state.pending_hunt = {'phase': 'hunt_sacrifice', 'damage': 1}
        self.assertIsNone(gl.check_ring_victory(state)['victory'])
        state.pending_hunt = None
        state.fellowship.corruption = 12
        self.assertEqual(gl.check_ring_victory(state)['victory'], 'shadow')
        state.fellowship.corruption = 11
        self.assertEqual(gl.check_ring_victory(state)['victory'], 'free_peoples')

    def test_military_victory_waits_until_end_of_turn(self):
        """Rulebook p44: military victory is assessed in Victory Check phase."""
        state = fresh()
        state.enemy_controlled[FP] = {'orthanc', 'moria'}
        result = gl.check_all_victory_conditions(state)
        self.assertEqual(result['victory'], 'free_peoples')
        self.assertEqual(result['free_peoples_vp'], 4)
        self.assertFalse(gl.should_game_end(result, end_of_turn=False))
        self.assertTrue(gl.should_game_end(result, end_of_turn=True))


class ChoiceIntegrity(unittest.TestCase):
    def test_broken_option_enumerator_does_not_mean_no_legal_choices(self):
        """A software failure must not silently replace a player decision."""
        state = fresh()
        with patch.dict(card_options.CARD_OPTION_SPECS, {
                'wisdom of elrond': lambda *_: (_ for _ in ()).throw(
                    ValueError('broken option enumeration'))}):
            with self.assertRaisesRegex(ValueError, 'broken option enumeration'):
                card_options.get_card_options(state, FP, 'Wisdom of Elrond')

    def test_option_failure_does_not_spend_player_card_or_die(self):
        import ai
        state = fresh()
        card_id = 'FREE_PEOPLES_Strategy_Wisdom_of_Elrond'
        state.hands[FP].hand = [card_id]
        dice(state, FP, gs.ActionDieFace.MUSTER)
        with patch.dict(card_options.CARD_OPTION_SPECS, {
                'wisdom of elrond': lambda *_: (_ for _ in ()).throw(
                    ValueError('broken option enumeration'))}):
            with self.assertRaisesRegex(RuntimeError, 'card option spec FAILED'):
                ai._execute_action(state, ai.Action(0, 'play_event', {
                    'card_id': card_id, 'side': 'fp'}))
        self.assertEqual(state.hands[FP].hand, [card_id])
        self.assertFalse(state.dice[FP][0].used)


class ScriptedCombatRules(unittest.TestCase):
    def test_ent_rage_and_deadly_strife_natural_one_still_gets_leader_reroll(self):
        """Rulebook p29/30: natural 1 misses even with +4, and may be rerolled.

        Legal card combination: FP Treebeard/Ent's Rage (+2 combat),
        SH Return to Valinor/Deadly Strife (+2 both players' rolls).
        Defending Edoras satisfies Ent's Rage's Rohan requirement.
        """
        state = fresh()
        place(state, 'westemnet', gs.Nation.ISENGARD, 2)
        defenders = place(state, 'edoras', gs.Nation.ROHAN, 1)
        defenders.leaders.append(gs.Leader(gs.Nation.ROHAN))
        sh_card = cards.get_card('SHADOW_Strategy_Return_to_Valinor')
        fp_card = cards.get_card('FREE_PEOPLES_Character_The_Ents_Awake:_Treebeard')
        battle = combat.setup_combat(state, 'westemnet', 'edoras',
            attacker_card=sh_card.to_combat_card(),
            defender_card=fp_card.to_combat_card())
        self.assertTrue(cards.can_play_combat_card(fp_card, battle, False, state)[0])
        with patch.object(combat, 'roll_d6_batch',
                          side_effect=[[1, 1], [1], [6]]) as roller:
            combat.resolve_combat_round(battle)
        self.assertEqual(battle.defender_dice_mod, 4)
        self.assertEqual(battle.defender_combat_rolls, [1])
        self.assertEqual(battle.defender_rerolls, [6])
        self.assertEqual(battle.defender_final_hits, 1)
        self.assertEqual(len(battle.attacker_army.units), 1)
        self.assertEqual(len(battle.defender_army.units), 1)
        self.assertEqual(roller.call_count, 3)

    def test_city_first_round_fives_miss_for_attacker(self):
        """Rulebook p29/31: attacking a City hits only on six in round one."""
        state = fresh()
        place(state, 'west harondor', gs.Nation.SAURON, 2)
        place(state, 'pelargir', gs.Nation.GONDOR, 1)
        battle = combat.setup_combat(state, 'west harondor', 'pelargir')
        with patch.object(combat, 'roll_d6_batch', side_effect=[[5, 1], [5]]):
            combat.resolve_combat_round(battle)
        self.assertEqual((battle.attacker_final_hits, battle.defender_final_hits), (0, 1))
        self.assertEqual(len(battle.attacker_army.units), 1)
        self.assertEqual(len(battle.defender_army.units), 1)

    def test_field_battle_casualties_are_simultaneous(self):
        """Rulebook p30: defender still deals its hit when its last unit dies."""
        state = fresh()
        place(state, 'dagorlad', gs.Nation.SAURON, 2)
        place(state, 'north ithilien', gs.Nation.GONDOR, 1)
        battle = combat.setup_combat(state, 'dagorlad', 'north ithilien')
        with patch.object(combat, 'roll_d6_batch', side_effect=[[5, 1], [5]]):
            combat.resolve_combat_round(battle)
        self.assertEqual((battle.attacker_final_hits, battle.defender_final_hits), (1, 1))
        self.assertEqual(len(battle.attacker_army.units), 1)
        self.assertEqual(len(battle.defender_army.units), 0)
        self.assertTrue(battle.defender_destroyed)


